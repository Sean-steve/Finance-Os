'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const port=8916,base='http://127.0.0.1:'+port+'/v3/';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function run(){
 const server=spawn('python3',['-m','http.server',String(port),'--bind','127.0.0.1'],{
  cwd:root,stdio:'ignore'});
 let browser;
 try{
  await sleep(600);
  browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const network=[];page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:'+port+'/v3/'))network.push(r.url());});
  await page.goto(base,{waitUntil:'load'});
  await page.getByRole('heading',{name:/financial clarity/i}).waitFor();
  assert.equal(await page.locator('.sidebar').count(),0,'auth/welcome stays outside nav');
  await page.getByRole('button',{name:/Explore interactive preview/i}).click();
  await page.getByRole('heading',{name:/Good (morning|afternoon|evening)/}).waitFor();
  const navNames=await page.locator('.sidebar nav .nav-item span').allTextContents();
  assert.deepEqual(navNames,['Home','Activity','Spending','Cash Flow','Goals','Wealth','Insights','Settings']);
  assert.ok(!navNames.some(x=>/\d|Welcome|Authentication/i.test(x)));
  assert.ok((await page.locator('.position-card h2').innerText()).includes('KES'));
  assert.equal(await page.locator('svg[data-unknown-chart]').count(),0);
  assert.ok(await page.getByText('Money in and out').count()>0);
  await page.locator('[data-period="3"]').click();
  assert.equal(await page.locator('[data-period="3"]').getAttribute('aria-pressed'),'true');
  await page.locator('[data-chart-index="0"]').click();
  assert.match(await page.locator('.chart-tooltip').innerText(),/KES .* in/);
  await page.locator('.topbar [data-open="quick"]').click();
  await page.getByRole('dialog').getByRole('button',{name:/Record transaction/i}).click();
  await page.locator('.drawer [name="title"]').fill('Investor preview groceries');
  await page.locator('.drawer [name="amount"]').fill('1234.50');
  await page.locator('.drawer [name="category"]').selectOption('Food');
  await page.locator('.drawer button[type="submit"]').click();
  await page.getByText('Preview transaction recorded. No backend posting occurred.').waitFor();
  await page.locator('.sidebar nav [data-go="activity"]').click();
  await page.getByText('Investor preview groceries').waitFor();
  await page.locator('.sidebar nav [data-go="spending"]').click();
  await page.getByRole('heading',{name:'Spending',exact:true}).waitFor();
  await page.locator('[data-open="budget"]').first().click();
  await page.locator('.drawer [name="amount"]').fill('21000');
  await page.waitForTimeout(3900); // An older toast must not wipe a partially filled form.
  assert.equal(await page.locator('.drawer [name="amount"]').inputValue(),'21000','Toast dismissal erased input');
  await page.locator('.drawer button[type="submit"]').click();
  await page.getByText('Monthly planning budget updated.').waitFor({timeout:5000});
  await page.locator('.sidebar nav [data-go="cash-flow"]').click();
  await page.getByRole('heading',{name:'Cash Flow',exact:true}).waitFor();
  await page.locator('[data-open="bill"]').first().click();
  await page.locator('.drawer [name="title"]').fill('Prototype school fees');
  await page.locator('.drawer [name="amount"]').fill('6500');
  await page.locator('.drawer button[type="submit"]').click();
  await page.getByText('Prototype school fees').waitFor();
  await page.locator('.sidebar nav [data-go="goals"]').click();
  await page.getByRole('heading',{name:'Goals',exact:true}).waitFor();
  await page.locator('[data-open="goal"]').first().click();
  await page.locator('.drawer [name="title"]').fill('Family holiday');
  await page.locator('.drawer [name="amount"]').fill('90000');
  await page.locator('.drawer button[type="submit"]').click();
  await page.getByText('Family holiday').waitFor();
  await page.locator('.sidebar nav [data-go="wealth"]').click();
  await page.getByText('Illustrative estimated net worth').waitFor();
  await page.locator('.sidebar nav [data-go="insights"]').click();
  await page.getByText('Rule-based insights only.').waitFor();
  await page.locator('.sidebar nav [data-go="settings"]').click();
  await page.getByText('Sample workspace').first().waitFor();
  await page.screenshot({path:'qa-artifacts/ux1-v3-desktop.png',fullPage:true});
  await page.locator('[data-action="reset-empty"]').click();
  await page.locator('.sidebar nav [data-go="home"]').click();
  await page.getByText('No records yet').waitFor();
  assert.equal(errors.length,0,'desktop has no browser runtime errors: '+errors.join(', '));
  assert.equal(network.length,0,'UX1 makes no external network requests: '+network.join(', '));

  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto(base,{waitUntil:'load'});
  await mobile.getByRole('button',{name:/Explore interactive preview/i}).click();
  await mobile.locator('.mobile-nav').waitFor();
  assert.equal(await mobile.locator('.mobile-nav button').count(),5);
  assert.equal(await mobile.locator('.sidebar').isVisible(),false);
  await mobile.locator('.mobile-nav [data-go="more"]').click();
  await mobile.getByRole('dialog',{name:'More destinations'}).waitFor();
  await mobile.getByRole('dialog').locator('[data-go="cash-flow"]').click();
  await mobile.getByRole('heading',{name:'Cash Flow',exact:true}).waitFor();
  const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth);
  assert.ok(overflow<=2,'Mobile horizontal page overflow: '+overflow);
  await mobile.locator('.mobile-nav [data-go="home"]').click();
  await mobile.screenshot({path:'qa-artifacts/ux1-v3-mobile.png',fullPage:true});
  assert.equal(errors.length,0,'mobile has no runtime errors: '+errors.join(', '));
  await mobile.close();
  const fresh=await browser.newPage({viewport:{width:1024,height:768}});
  await fresh.goto(base);
  await fresh.locator('[data-action="auth"]').click();
  await fresh.getByRole('heading',{name:/calmer way to manage money/i}).waitFor();
  assert.equal(await fresh.locator('input:disabled').count(),2,'UX1 sign-in must never collect credentials');
  await fresh.locator('[data-action="welcome"]').click();
  await fresh.locator('[data-action="onboarding"]').click();
  await fresh.locator('[data-form="onboarding"] [name="firstName"]').fill('Tester');
  await fresh.locator('[data-form="onboarding"] button[type="submit"]').click();
  await fresh.getByText('No records yet').waitFor();
  await fresh.locator('[data-open="account"]').first().click();
  await fresh.locator('.drawer [name="name"]').fill('Manual wallet');
  await fresh.locator('.drawer button[type="submit"]').click();
  await fresh.locator('[data-open="transaction"]').first().click();
  await fresh.locator('.drawer [name="kind"]').selectOption('income');
  await fresh.locator('.drawer [name="title"]').fill('First illustrative income');
  await fresh.locator('.drawer [name="amount"]').fill('5000');
  await fresh.locator('.drawer button[type="submit"]').click();
  await fresh.locator('.position-card h2').getByText(/KES 5,000/).waitFor();
  await fresh.close();
  console.log('PASS UX1 Chromium: welcome, no-credential sign-in, onboarding/empty-to-first-value, all 8 destinations, charts, transaction, budget, bill, goals, desktop and mobile responsive, zero external requests.');
 }finally{
  if(browser)await browser.close();
  server.kill('SIGTERM');
 }
}
(async()=>{
 fs.mkdirSync(path.join(root,'qa-artifacts'),{recursive:true});
 await run();
})().catch(e=>{console.error(e.stack||e);process.exitCode=1;});
